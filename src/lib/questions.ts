// Собираем текст заявки из ответов. Принимаем только варианты из списка вопросов.
export function composeRequest(catTitle: string, cityName: string | undefined, cat: string, answers: Record<string, unknown> | undefined, note: string): string {
  const parts: string[] = []
  for (const qq of questionsFor(cat)) {
    const a = answers?.[qq.id]
    if (typeof a === 'string' && qq.options.includes(a)) parts.push(`${qq.title.replace(/\?$/, '')}: ${a}`)
  }
  const head = `Заявка: ${catTitle}${cityName ? `, ${cityName}` : ''}.`
  return [head, parts.length ? parts.join('. ') + '.' : '', note].filter(Boolean).join(' ')
}
